import { execFileSync, spawnSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { expect, it } from "vitest";

const cli = path.resolve(import.meta.dirname, "../bin/check-commit.mjs");
const installer = path.resolve(import.meta.dirname, "../bin/install-hooks.mjs");

it.each([
  "fix: handle errors\n\nCo-Authored-By: Claude <bot@example.com>",
  "fix: handle errors\r\n\r\nco-authored-by: GPT-6 <bot@example.com>",
  "feat: add page\n\nGenerated with Cursor",
  "feat: add page\n\n🤖 Generated by Codex",
  "fix: handle errors\n\nCo-authored-by: Assistant <noreply@anthropic.com>",
  "fix: handle errors\n\nAssisted-by: Gemini",
])("rejects model and tool attribution: %s", (message) => {
  const directory = mkdtempSync(path.join(tmpdir(), "commit message "));
  try {
    const file = path.join(directory, "message.txt");
    writeFileSync(file, message);
    const result = spawnSync(process.execPath, [cli, file], {
      encoding: "utf8",
      windowsHide: true,
    });
    expect(result.status).toBe(1);
    expect(result.stderr).toMatch(/attribution/i);
  } finally {
    rmSync(directory, { recursive: true, force: true });
  }
});

it("keeps human coauthors and ordinary technical mentions", () => {
  const directory = mkdtempSync(path.join(tmpdir(), "commit message "));
  try {
    const file = path.join(directory, "message.txt");
    writeFileSync(file, "fix: support Claude API errors\n\nCo-Authored-By: Jane Doe <jane@example.com>");
    expect(spawnSync(process.execPath, [cli, file], { windowsHide: true }).status).toBe(0);
    expect(spawnSync(process.execPath, [cli], { windowsHide: true }).status).toBe(2);
  } finally {
    rmSync(directory, { recursive: true, force: true });
  }
});

it("installs an idempotent Git hook that rejects commits on Windows and preserves a foreign hook", () => {
  const directory = mkdtempSync(path.join(tmpdir(), "harness hooks "));
  const git = (...args: string[]) => execFileSync("git", args, { cwd: directory, encoding: "utf8", windowsHide: true });
  try {
    git("init", "--quiet");
    git("config", "user.name", "Hook Test");
    git("config", "user.email", "test@example.com");
    expect(spawnSync(process.execPath, [installer], { cwd: directory, windowsHide: true }).status).toBe(0);
    expect(spawnSync(process.execPath, [installer], { cwd: directory, windowsHide: true }).status).toBe(0);
    const file = path.join(directory, "message.txt");
    writeFileSync(file, "fix: example\n\nGenerated with Codex");
    expect(
      spawnSync("git", ["commit", "--allow-empty", "-F", file], {
        cwd: directory,
        windowsHide: true,
      }).status,
    ).toBe(1);
    writeFileSync(file, "fix: example");
    expect(
      spawnSync("git", ["commit", "--allow-empty", "-F", file], {
        cwd: directory,
        windowsHide: true,
      }).status,
    ).toBe(0);
    const hook = path.join(directory, ".git/hooks/commit-msg");
    writeFileSync(hook, "#!/bin/sh\nexit 7\n");
    expect(spawnSync(process.execPath, [installer], { cwd: directory, windowsHide: true }).status).toBe(2);
    expect(readFileSync(hook, "utf8")).toBe("#!/bin/sh\nexit 7\n");
    git("config", "core.hooksPath", ".custom hooks");
    expect(spawnSync(process.execPath, [installer], { cwd: directory, windowsHide: true }).status).toBe(0);
    writeFileSync(file, "fix: custom hooks\n\nCo-Authored-By: Claude <bot@example.com>");
    expect(
      spawnSync("git", ["commit", "--allow-empty", "-F", file], {
        cwd: directory,
        windowsHide: true,
      }).status,
    ).toBe(1);
  } finally {
    rmSync(directory, { recursive: true, force: true });
  }
});
